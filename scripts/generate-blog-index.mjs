import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { blogArticles, blogCategories, coreBlogArticles } from '../src/content/blogArticles.js';
import { getBlogArticlesForLocale } from '../src/content/localizedBlogArticles.js';
import { buyerGuides } from '../src/content/buyerGuides/index.js';

const fields = ['slug', 'title', 'description', 'category', 'date', 'updated', 'readTime', 'featured', 'keywords'];
const summarize = (article) => Object.fromEntries(fields.map((field) => [field, article[field]]));
const archiveCatalogs = Object.fromEntries(['pt', 'en', 'es'].map((locale) => [
  locale, getBlogArticlesForLocale(locale).map(summarize),
]));
const catalogs = Object.fromEntries(Object.entries(archiveCatalogs).map(([locale, articles]) => {
  const localizedBySlug = new Map(articles.map((article) => [article.slug, article]));
  return [locale, coreBlogArticles.map(({ slug }) => localizedBySlug.get(slug)).filter(Boolean)];
}));

const source = `// Generated by scripts/generate-blog-index.mjs.\nexport const blogArticleCounts = ${JSON.stringify(Object.fromEntries(['pt', 'en', 'es'].map((locale) => [locale, getBlogArticlesForLocale(locale).length])))};\nexport const blogIndexArticles = ${JSON.stringify(catalogs, null, 2)};\n`;
await writeFile(resolve('src/content/blogIndexArticles.generated.js'), source);
const archiveSource = `// Generated by scripts/generate-blog-index.mjs.\nexport const blogArchiveArticles = ${JSON.stringify(archiveCatalogs)};\nexport const blogArchiveCategories = ${JSON.stringify(blogCategories)};\n`;
await writeFile(resolve('src/content/blogArchiveArticles.generated.js'), archiveSource);

const publishedBySlug = new Map(blogArticles.map((article) => [article.slug, article]));
const buyerGuideLinksByService = {};
for (const guide of buyerGuides) {
  const { slug, title, updated, primaryGuide } = publishedBySlug.get(guide.slug);
  const links = buyerGuideLinksByService[primaryGuide.href] ??= [];
  if (links.length < 4) links.push({ href: `/blog/${slug}`, label: title, updated });
}
const serviceSource = `// Generated by scripts/generate-blog-index.mjs.\nexport const buyerGuideLinksByService = ${JSON.stringify(buyerGuideLinksByService, null, 2)};\n`;
await writeFile(resolve('src/content/buyerGuideLinks.generated.js'), serviceSource);
console.log(`Generated lightweight blog catalog with ${catalogs.pt.length} core articles in 3 languages.`);
