import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { coreBlogArticles } from '../src/content/blogArticles.js';
import { getBlogArticlesForLocale } from '../src/content/localizedBlogArticles.js';

const fields = ['slug', 'title', 'description', 'category', 'date', 'updated', 'readTime', 'featured', 'keywords'];
const summarize = (article) => Object.fromEntries(fields.map((field) => [field, article[field]]));
const catalogs = Object.fromEntries(['pt', 'en', 'es'].map((locale) => {
  const localizedBySlug = new Map(getBlogArticlesForLocale(locale).map((article) => [article.slug, article]));
  return [locale, coreBlogArticles.map(({ slug }) => localizedBySlug.get(slug)).filter(Boolean).map(summarize)];
}));

const source = `// Generated by scripts/generate-blog-index.mjs.\nexport const blogArticleCounts = ${JSON.stringify(Object.fromEntries(['pt', 'en', 'es'].map((locale) => [locale, getBlogArticlesForLocale(locale).length])))};\nexport const blogIndexArticles = ${JSON.stringify(catalogs, null, 2)};\n`;
await writeFile(resolve('src/content/blogIndexArticles.generated.js'), source);
console.log(`Generated lightweight blog catalog with ${catalogs.pt.length} core articles in 3 languages.`);
